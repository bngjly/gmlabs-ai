// 当前语言（持久化）
window.CURRENT_LANG = localStorage.getItem('lang') || 'zh';

window.t = function(key) {
  return (window.I18N[window.CURRENT_LANG] && window.I18N[window.CURRENT_LANG][key])
      || window.I18N.zh[key]
      || key;
};

window.applyI18n = function() {
  document.documentElement.lang = window.CURRENT_LANG === 'zh' ? 'zh-CN' : 'en';
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const attr = el.getAttribute('data-i18n-attr');  // 可选：'placeholder', 'title' 等
    if (attr) el.setAttribute(attr, window.t(key));
    else el.innerHTML = window.t(key);
  });
};

window.setLang = function(lang) {
  window.CURRENT_LANG = lang;
  localStorage.setItem('lang', lang);
  window.applyI18n();
  // 触发动态内容重渲染
  if (typeof renderHomeStats === 'function') renderHomeStats();
  if (typeof renderProfile === 'function') renderProfile();
};
